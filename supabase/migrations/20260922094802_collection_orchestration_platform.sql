CREATE OR REPLACE FUNCTION public.create_collection_run(
  p_workflow_id bigint,
  p_config_override jsonb DEFAULT '{}'::jsonb,
  p_rule_snapshot jsonb DEFAULT '{}'::jsonb,
  p_strategy_snapshot jsonb DEFAULT '{}'::jsonb,
  p_parent_run_id uuid DEFAULT NULL
)
RETURNS SETOF public.collection_runs
LANGUAGE plpgsql
AS $$
DECLARE
  workflow_row public.collection_workflows%ROWTYPE;
  snapshot jsonb;
BEGIN
  SELECT * INTO workflow_row
  FROM public.collection_workflows
  WHERE id = p_workflow_id AND enabled
  FOR SHARE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'workflow is not enabled or does not exist' USING ERRCODE = 'P0002';
  END IF;

  SELECT jsonb_build_object(
    'id', workflow_row.id,
    'name', workflow_row.name,
    'revision', workflow_row.revision,
    'default_config', workflow_row.default_config,
    'retention_config', workflow_row.retention_config,
    'steps', COALESCE((
      SELECT jsonb_agg(jsonb_build_object(
        'id', s.id, 'script_id', s.script_id, 'step_key', s.step_key, 'seq', s.seq,
        'enabled', s.enabled, 'config_override', s.config_override, 'condition', s.condition,
        'continue_on_error', s.continue_on_error, 'retry_count', s.retry_count,
        'timeout_seconds', s.timeout_seconds, 'script_snapshot', to_jsonb(cs)
      ) ORDER BY s.seq, s.id)
      FROM public.collection_workflow_steps s
      JOIN public.collector_scripts cs ON cs.id = s.script_id
      WHERE s.workflow_id = workflow_row.id
    ), '[]'::jsonb)
  ) INTO snapshot;

  RETURN QUERY
  INSERT INTO public.collection_runs(workflow_id, workflow_snapshot, status, config_snapshot, rule_snapshot, strategy_snapshot, parent_run_id)
  VALUES(workflow_row.id, snapshot, 'queued', COALESCE(workflow_row.default_config, '{}'::jsonb) || COALESCE(p_config_override, '{}'::jsonb), COALESCE(p_rule_snapshot, '{}'::jsonb), COALESCE(p_strategy_snapshot, '{}'::jsonb), p_parent_run_id)
  RETURNING *;
END;
$$;

CREATE OR REPLACE FUNCTION public.claim_collection_run(
  p_worker_id text,
  p_lease_seconds integer DEFAULT 120
)
RETURNS SETOF public.collection_runs
LANGUAGE plpgsql
AS $$
BEGIN
  IF btrim(COALESCE(p_worker_id, '')) = '' OR p_lease_seconds <= 0 OR p_lease_seconds > 86400 THEN
    RAISE EXCEPTION 'invalid worker lease' USING ERRCODE = '22023';
  END IF;
  UPDATE public.collection_runs
  SET status = 'interrupted', finished_at = now(), lease_until = NULL,
      summary = COALESCE(summary, '{}'::jsonb) || jsonb_build_object('recovery', 'lease_expired')
  WHERE status = 'running' AND lease_until IS NOT NULL AND lease_until <= now();
  RETURN QUERY
  WITH candidate AS (
    SELECT id
    FROM public.collection_runs
    WHERE status IN ('queued', 'retrying')
    ORDER BY created_at, id
    FOR UPDATE SKIP LOCKED
    LIMIT 1
  )
  UPDATE public.collection_runs r
  SET status = 'running', worker_id = p_worker_id,
      lease_until = now() + make_interval(secs => p_lease_seconds),
      heartbeat_at = now(), started_at = COALESCE(started_at, now())
  FROM candidate
  WHERE r.id = candidate.id
  RETURNING r.*;
END;
$$;

CREATE OR REPLACE FUNCTION public.heartbeat_collection_run(
  p_run_id uuid,
  p_worker_id text,
  p_lease_seconds integer DEFAULT 120
)
RETURNS boolean
LANGUAGE plpgsql
AS $$
DECLARE
  changed integer;
BEGIN
  IF p_lease_seconds <= 0 OR p_lease_seconds > 86400 THEN
    RAISE EXCEPTION 'invalid lease' USING ERRCODE = '22023';
  END IF;
  UPDATE public.collection_runs
  SET lease_until = now() + make_interval(secs => p_lease_seconds), heartbeat_at = now()
  WHERE id = p_run_id AND status = 'running' AND worker_id = p_worker_id AND lease_until > now();
  GET DIAGNOSTICS changed = ROW_COUNT;
  RETURN changed = 1;
END;
$$;

CREATE OR REPLACE FUNCTION public.reorder_collection_workflow_steps(
  p_workflow_id bigint,
  p_steps jsonb
)
RETURNS SETOF public.collection_workflow_steps
LANGUAGE plpgsql
AS $$
DECLARE
  requested_count integer;
  actual_count integer;
  sequence_offset integer;
BEGIN
  IF jsonb_typeof(p_steps) <> 'array' THEN
    RAISE EXCEPTION 'steps must be an array' USING ERRCODE = '22023';
  END IF;
  PERFORM 1 FROM public.collection_workflows WHERE id = p_workflow_id FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'workflow does not exist' USING ERRCODE = 'P0002';
  END IF;
  SELECT count(*) INTO requested_count FROM jsonb_array_elements(p_steps);
  SELECT count(*) INTO actual_count FROM public.collection_workflow_steps WHERE workflow_id = p_workflow_id;
  IF requested_count <> actual_count THEN
    RAISE EXCEPTION 'step list is not complete' USING ERRCODE = '22023';
  END IF;

  SELECT COALESCE(max(seq), 0) + actual_count + 1 INTO sequence_offset
  FROM public.collection_workflow_steps
  WHERE workflow_id = p_workflow_id;
  UPDATE public.collection_workflow_steps
  SET seq = seq + sequence_offset
  WHERE workflow_id = p_workflow_id;

  UPDATE public.collection_workflow_steps target
  SET seq = source.seq
  FROM (
    SELECT (value->>'id')::bigint AS id, (value->>'seq')::integer AS seq
    FROM jsonb_array_elements(p_steps)
  ) source
  WHERE target.id = source.id AND target.workflow_id = p_workflow_id AND source.seq >= 0;

  IF (SELECT count(*) FROM public.collection_workflow_steps WHERE workflow_id = p_workflow_id AND seq >= 0) <> actual_count THEN
    RAISE EXCEPTION 'step list contains an unknown id or invalid sequence' USING ERRCODE = '22023';
  END IF;
  RETURN QUERY SELECT * FROM public.collection_workflow_steps WHERE workflow_id = p_workflow_id ORDER BY seq, id;
END;
$$;

