CREATE OR REPLACE FUNCTION public.collection_orchestration_set_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$;

DO $$
DECLARE
  table_name text;
BEGIN
  FOREACH table_name IN ARRAY ARRAY['collector_scripts', 'collection_workflows', 'collection_workflow_steps', 'collection_runs', 'collection_step_runs'] LOOP
    EXECUTE format('DROP TRIGGER IF EXISTS %I ON public.%I', table_name || '_set_updated_at', table_name);
    EXECUTE format('CREATE TRIGGER %I BEFORE UPDATE ON public.%I FOR EACH ROW EXECUTE FUNCTION public.collection_orchestration_set_updated_at()', table_name || '_set_updated_at', table_name);
  END LOOP;
END;
$$;

