SET LOCAL lock_timeout = '5s';

CREATE TABLE public.collector_scripts (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(160) NOT NULL,
  script_key varchar(128) NOT NULL,
  platform varchar(64) NOT NULL,
  description text NOT NULL DEFAULT '',
  execution_type varchar(32) NOT NULL DEFAULT 'node',
  entrypoint text NOT NULL,
  enabled boolean NOT NULL DEFAULT true,
  version integer NOT NULL DEFAULT 1,
  timeout_seconds integer NOT NULL DEFAULT 900,
  retry_count smallint NOT NULL DEFAULT 0,
  default_config jsonb NOT NULL DEFAULT '{}'::jsonb,
  input_schema jsonb NOT NULL DEFAULT '{}'::jsonb,
  output_schema jsonb NOT NULL DEFAULT '{}'::jsonb,
  code_hash text NOT NULL,
  capabilities jsonb NOT NULL DEFAULT '[]'::jsonb,
  credential_ref text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT collector_scripts_key_version_unique UNIQUE (script_key, version),
  CONSTRAINT collector_scripts_execution_type_check CHECK (execution_type = 'node'),
  CONSTRAINT collector_scripts_version_check CHECK (version >= 1),
  CONSTRAINT collector_scripts_timeout_check CHECK (timeout_seconds > 0),
  CONSTRAINT collector_scripts_retry_check CHECK (retry_count >= 0 AND retry_count <= 10),
  CONSTRAINT collector_scripts_entrypoint_check CHECK (btrim(entrypoint) <> ''),
  CONSTRAINT collector_scripts_hash_check CHECK (btrim(code_hash) <> ''),
  CONSTRAINT collector_scripts_capabilities_check CHECK (jsonb_typeof(capabilities) = 'array')
);

CREATE TABLE public.collection_workflows (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(160) NOT NULL,
  enabled boolean NOT NULL DEFAULT true,
  revision integer NOT NULL DEFAULT 1,
  default_config jsonb NOT NULL DEFAULT '{}'::jsonb,
  retention_config jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT collection_workflows_revision_check CHECK (revision >= 1)
);

CREATE TABLE public.collection_workflow_steps (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workflow_id bigint NOT NULL REFERENCES public.collection_workflows(id) ON DELETE CASCADE,
  script_id bigint NOT NULL REFERENCES public.collector_scripts(id) ON DELETE RESTRICT,
  step_key varchar(128) NOT NULL,
  seq integer NOT NULL,
  enabled boolean NOT NULL DEFAULT true,
  config_override jsonb NOT NULL DEFAULT '{}'::jsonb,
  condition jsonb,
  continue_on_error boolean NOT NULL DEFAULT false,
  retry_count smallint NOT NULL DEFAULT 0,
  timeout_seconds integer,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT collection_workflow_steps_key_unique UNIQUE (workflow_id, step_key),
  CONSTRAINT collection_workflow_steps_seq_unique UNIQUE (workflow_id, seq),
  CONSTRAINT collection_workflow_steps_seq_check CHECK (seq >= 0),
  CONSTRAINT collection_workflow_steps_retry_check CHECK (retry_count >= 0 AND retry_count <= 10),
  CONSTRAINT collection_workflow_steps_timeout_check CHECK (timeout_seconds IS NULL OR timeout_seconds > 0),
  CONSTRAINT collection_workflow_steps_condition_check CHECK (condition IS NULL OR jsonb_typeof(condition) = 'object')
);

CREATE TABLE public.collection_runs (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  workflow_id bigint REFERENCES public.collection_workflows(id) ON DELETE RESTRICT,
  workflow_snapshot jsonb NOT NULL DEFAULT '{}'::jsonb,
  status varchar(32) NOT NULL DEFAULT 'queued',
  config_snapshot jsonb NOT NULL DEFAULT '{}'::jsonb,
  rule_snapshot jsonb NOT NULL DEFAULT '{}'::jsonb,
  strategy_snapshot jsonb NOT NULL DEFAULT '{}'::jsonb,
  started_at timestamptz,
  finished_at timestamptz,
  summary jsonb NOT NULL DEFAULT '{}'::jsonb,
  parent_run_id uuid REFERENCES public.collection_runs(id) ON DELETE SET NULL,
  worker_id varchar(160),
  lease_until timestamptz,
  heartbeat_at timestamptz,
  publish_status varchar(32) NOT NULL DEFAULT 'not_requested',
  artifact_manifest jsonb NOT NULL DEFAULT '{}'::jsonb,
  retention_until timestamptz,
  pinned boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT collection_runs_status_check CHECK (status IN ('queued', 'pending', 'running', 'retrying', 'timed_out', 'cancelled', 'blocked', 'interrupted', 'success', 'partial', 'failed', 'waiting_auth')),
  CONSTRAINT collection_runs_publish_status_check CHECK (publish_status IN ('not_requested', 'preview', 'queued', 'committing', 'partial', 'confirmed', 'failed', 'unknown', 'finalized')),
  CONSTRAINT collection_runs_snapshot_check CHECK (jsonb_typeof(workflow_snapshot) = 'object' AND jsonb_typeof(config_snapshot) = 'object' AND jsonb_typeof(rule_snapshot) = 'object' AND jsonb_typeof(strategy_snapshot) = 'object')
);

CREATE TABLE public.collection_step_runs (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  run_id uuid NOT NULL REFERENCES public.collection_runs(id) ON DELETE CASCADE,
  step_key varchar(128) NOT NULL,
  script_snapshot jsonb NOT NULL DEFAULT '{}'::jsonb,
  attempt integer NOT NULL DEFAULT 1,
  status varchar(32) NOT NULL DEFAULT 'pending',
  started_at timestamptz,
  finished_at timestamptz,
  duration_ms bigint,
  input_count bigint,
  output_count bigint,
  created_count bigint,
  updated_count bigint,
  filtered_count bigint,
  request_count bigint,
  error_code varchar(128),
  error_message text,
  checkpoint jsonb NOT NULL DEFAULT '{}'::jsonb,
  artifact_manifest jsonb NOT NULL DEFAULT '{}'::jsonb,
  log_ref text,
  input_hash text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT collection_step_runs_attempt_unique UNIQUE (run_id, step_key, attempt),
  CONSTRAINT collection_step_runs_status_check CHECK (status IN ('pending', 'running', 'retrying', 'timed_out', 'cancelled', 'blocked', 'interrupted', 'success', 'partial', 'failed', 'waiting_auth', 'skipped')),
  CONSTRAINT collection_step_runs_duration_check CHECK (duration_ms IS NULL OR duration_ms >= 0),
  CONSTRAINT collection_step_runs_counts_check CHECK (
    (input_count IS NULL OR input_count >= 0) AND
    (output_count IS NULL OR output_count >= 0) AND
    (created_count IS NULL OR created_count >= 0) AND
    (updated_count IS NULL OR updated_count >= 0) AND
    (filtered_count IS NULL OR filtered_count >= 0) AND
    (request_count IS NULL OR request_count >= 0)
  )
);

