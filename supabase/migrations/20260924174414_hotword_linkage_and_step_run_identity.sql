CREATE OR REPLACE FUNCTION public.sync_collection_step_run_identity()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = pg_catalog, public
AS $$
BEGIN
  IF TG_OP = 'INSERT' THEN
    IF NEW.run_id IS NULL THEN NEW.run_id := NEW.workflow_run_id; END IF;
    IF NEW.workflow_run_id IS NULL THEN NEW.workflow_run_id := NEW.run_id; END IF;
  ELSIF NEW.run_id IS DISTINCT FROM OLD.run_id THEN
    NEW.workflow_run_id := NEW.run_id;
  ELSIF NEW.workflow_run_id IS DISTINCT FROM OLD.workflow_run_id THEN
    NEW.run_id := NEW.workflow_run_id;
  END IF;
  IF NEW.script_id IS NULL AND NEW.step_id IS NOT NULL THEN
    SELECT script_id INTO NEW.script_id FROM public.collection_workflow_steps WHERE id = NEW.step_id;
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS collection_step_runs_identity_sync ON public.collection_step_runs;
CREATE TRIGGER collection_step_runs_identity_sync
BEFORE INSERT OR UPDATE ON public.collection_step_runs
FOR EACH ROW EXECUTE FUNCTION public.sync_collection_step_run_identity();

CREATE OR REPLACE FUNCTION public.create_collection_run_from_step(
  p_workflow_id bigint,
  p_step_id bigint,
  p_single_step boolean DEFAULT false,
  p_config_override jsonb DEFAULT '{}'::jsonb,
  p_rule_snapshot jsonb DEFAULT '{}'::jsonb,
  p_strategy_snapshot jsonb DEFAULT '{}'::jsonb,
  p_parent_run_id uuid DEFAULT NULL
)
RETURNS SETOF public.collection_runs
LANGUAGE plpgsql
SET search_path = pg_catalog, public
AS $$
DECLARE
  workflow_row public.collection_workflows%ROWTYPE;
  start_row public.collection_workflow_steps%ROWTYPE;
  snapshot jsonb;
BEGIN
  SELECT * INTO workflow_row FROM public.collection_workflows
  WHERE id = p_workflow_id AND enabled FOR SHARE;
  IF NOT FOUND THEN RAISE EXCEPTION '工作流未启用或不存在' USING ERRCODE = 'P0002'; END IF;

  SELECT * INTO start_row FROM public.collection_workflow_steps
  WHERE id = p_step_id AND workflow_id = p_workflow_id;
  IF NOT FOUND THEN RAISE EXCEPTION '步骤不属于该工作流或已删除' USING ERRCODE = 'P0002'; END IF;

  IF p_parent_run_id IS NOT NULL AND NOT EXISTS (
    SELECT 1 FROM public.collection_runs WHERE id = p_parent_run_id AND workflow_id = p_workflow_id
  ) THEN RAISE EXCEPTION '续跑来源运行不属于该工作流' USING ERRCODE = '22023'; END IF;

  SELECT jsonb_build_object(
    'id', workflow_row.id,
    'name', workflow_row.name,
    'enabled', workflow_row.enabled,
    'revision', workflow_row.revision,
    'default_config', workflow_row.default_config,
    'retention_config', workflow_row.retention_config,
    'steps', COALESCE((
      SELECT jsonb_agg(jsonb_build_object(
        'id', s.id, 'workflow_id', s.workflow_id, 'script_id', s.script_id,
        'step_key', s.step_key, 'seq', s.seq, 'enabled', s.enabled,
        'config_override', s.config_override, 'condition', s.condition,
        'continue_on_error', s.continue_on_error, 'retry_count', s.retry_count,
        'timeout_seconds', s.timeout_seconds, 'script_snapshot', to_jsonb(cs)
      ) ORDER BY s.seq, s.id)
      FROM public.collection_workflow_steps s
      JOIN public.collector_scripts cs ON cs.id = s.script_id
      WHERE s.workflow_id = workflow_row.id
        AND ((p_single_step AND s.id = start_row.id) OR (NOT p_single_step AND s.seq >= start_row.seq))
    ), '[]'::jsonb)
  ) INTO snapshot;

  RETURN QUERY
  INSERT INTO public.collection_runs(workflow_id, workflow_snapshot, status, config_snapshot, rule_snapshot, strategy_snapshot, parent_run_id)
  VALUES (
    workflow_row.id,
    snapshot,
    'queued',
    COALESCE(workflow_row.default_config, '{}'::jsonb) || COALESCE(p_config_override, '{}'::jsonb),
    COALESCE(p_rule_snapshot, '{}'::jsonb),
    COALESCE(p_strategy_snapshot, '{}'::jsonb),
    p_parent_run_id
  )
  RETURNING *;
END;
$$;

REVOKE EXECUTE ON FUNCTION public.create_collection_run_from_step(bigint, bigint, boolean, jsonb, jsonb, jsonb, uuid) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.create_collection_run_from_step(bigint, bigint, boolean, jsonb, jsonb, jsonb, uuid) TO service_role;

